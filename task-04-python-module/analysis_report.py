import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import base64
from io import BytesIO

def save_plot_to_base64():
    tmp_file = BytesIO()
    plt.savefig(tmp_file, format='png', bbox_inches='tight')
    plt.close()
    return base64.b64encode(tmp_file.getvalue()).decode('utf-8')

df = pd.read_csv("sneaker_sales_dataset.csv")
df['transaction_date'] = pd.to_datetime(df['transaction_date'])

plt.figure(figsize=(15, 5))
plt.subplot(1, 3, 1)
sns.boxplot(x=df['size_eu'], color='skyblue').set_title('Shoe Size')
plt.subplot(1, 3, 2)
sns.boxplot(x=df['price_per_pair'], color='lightgreen').set_title('Price per Pair')
plt.subplot(1, 3, 3)
sns.boxplot(x=df['customer_birth_year'], color='salmon').set_title('Birth Year')
graph_quality = save_plot_to_base64()

counts = df['brand'].value_counts()
plt.figure(figsize=(10, 5))
sns.barplot(x=counts.index, y=counts.values, hue=counts.index, palette='magma', legend=False)
plt.title('Transactions per Brand')
graph_brands = save_plot_to_base64()

total_revenue = df.groupby('brand')['final_price'].sum().sort_values(ascending=False)
df['month'] = df['transaction_date'].dt.to_period('M').astype(str)
monthly = df.groupby(['month', 'brand'])['final_price'].sum().unstack().fillna(0)

plt.figure(figsize=(10, 5))
sns.barplot(x=total_revenue.index, y=total_revenue.values, hue=total_revenue.index, palette='viridis', legend=False)
plt.title('Total Revenue by Brand')
graph_revenue = save_plot_to_base64()

plt.figure(figsize=(12, 5))
for brand in monthly.columns:
    plt.plot(monthly.index, monthly[brand], marker='o', label=brand)
plt.title('Monthly Sales Dynamics')
plt.legend(bbox_to_anchor=(1.05, 1))
graph_dynamics = save_plot_to_base64()

